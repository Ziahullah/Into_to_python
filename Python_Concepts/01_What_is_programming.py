# ============================================================
# 1. What is Programming?
# ============================================================

"""
Programming is the process of giving instructions to a computer
to perform a specific task.

A computer cannot think or make decisions on its own.
It follows the instructions that we provide.

We give these instructions using a programming language,
such as Python, C#, Java, or JavaScript.
"""


# ============================================================
# 🌍 A Simple Real-Life Example
# ============================================================

"""
Imagine you want to make a cup of tea.

You would give instructions like:

1. Boil water.
2. Add tea powder.
3. Add milk.
4. Add sugar.
5. Boil for a few minutes.
6. Pour the tea into a cup.

These are step-by-step instructions.

Similarly, when we want a computer to perform a task,
we give it step-by-step instructions using a programming language.
"""


# ============================================================
# 🐍 Example in Python
# ============================================================

# Suppose we want the computer to display "Hello World":

print("Hello World")

# Here:
# print() -> Tells Python to display something.
# "Hello World" -> The message we want to display.

# Output:
# Hello World


# ============================================================
# 💡 Simple Definition to Remember
# ============================================================

"""
Programming = Giving step-by-step instructions to a computer
              to perform a task.

Real life:
Instructions -> Person performs a task

Programming:
Instructions -> Computer performs a task
"""


# ============================================================
# 2. Why Do We Need Programming?
# ============================================================

"""
We need programming to tell computers what to do
and make our work easier and faster.

Programming helps us:

- Automate tasks
- Solve problems
- Save time
- Reduce manual work
- Build software and applications
"""


