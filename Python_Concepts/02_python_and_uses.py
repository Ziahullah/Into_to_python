# ============================================================
# A SMALL EXAMPLE OF PYTHON'S POWER
# ============================================================

# Python can calculate the average of students' marks
# using just a few lines of code.

marks = [80, 90, 70, 100]

average = sum(marks) / len(marks)

print("Average mark:", average)

# Output:
# Average mark: 85.0


